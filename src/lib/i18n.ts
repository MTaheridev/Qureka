const dictionaries: Record<AppLanguage, Dict> = { en, fa };

export type I18nKey = keyof typeof en;

export function t(language: AppLanguage, key: I18nKey, vars?: Record<string, string>): string {
  let text = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, value);
    }
  }
  return text;
}

export function dirFor(language: AppLanguage): 'ltr' | 'rtl' {
  return language === 'fa' ? 'rtl' : 'ltr';
}
